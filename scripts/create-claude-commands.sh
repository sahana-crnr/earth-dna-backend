#!/usr/bin/env bash
# ─────────────────────────────────────────────────────────────────────────────
# scripts/create-claude-commands.sh
# Creates all project-level Claude Code slash commands.
# Run once: bash scripts/create-claude-commands.sh
# ─────────────────────────────────────────────────────────────────────────────

set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
CMD="$ROOT/.claude/commands"
mkdir -p "$CMD"

# ── /sync ─────────────────────────────────────────────────────────────────────
cat > "$CMD/sync.md" << 'SYNC'
---
description: Re-read the daily context snapshot and summarise the current project state
---

Do the following in order:

1. Read `CLAUDE.md` to load project conventions, tech stack, and official documentation links.

2. Read `.claude/context.md` (generated by `npm run claude:sync`).
   If the file does not exist, tell the user to run `npm run claude:sync` first and stop.

3. Check the snapshot timestamp at the top of `.claude/context.md`.
   If it is older than 24 hours, warn the user to run `npm run claude:sync` to refresh.

4. Print a concise project status in this format:

---
### 📅 Snapshot date
<date from file>

### 🌿 Branch
<active branch>

### 🗂 Modules
List every module with status: ✅ complete | 🚧 scaffolded | ⚠️ needs entity/DTO

### 🗄 Entities
List all entity files, or "none yet"

### 📋 DTOs
List all DTO files, or "none yet"

### 🔄 Pending migrations
List migration files, or "none"

### 🔀 Uncommitted changes
Summarise dirty working tree (new/modified/deleted files)

### 🔖 Recent commits (last 5)
Show the 5 most recent commit one-liners

### 💡 Suggested next steps
Based on scaffolded-but-incomplete modules (no entity, no JWT, missing DTOs),
suggest the 2–3 highest-impact things to build next.
---

5. Ask: "What would you like to work on today?"
SYNC

echo "✅  Created: .claude/commands/sync.md  → use /sync"

# ── /feature ──────────────────────────────────────────────────────────────────
cat > "$CMD/feature.md" << 'FEATURE'
---
description: Scaffold a complete NestJS CRUD feature module (entity + DTOs + service + controller + module)
---

You are scaffolding a new NestJS feature module named: **$ARGUMENTS**

Read `CLAUDE.md` first to apply the project's naming conventions, patterns, and coding standards.

Generate ALL of the following files (no placeholders — fully working code):

1. **`src/$ARGUMENTS/$ARGUMENTS.entity.ts`**
   - UUID primary key (`@PrimaryGeneratedColumn('uuid')`)
   - `createdAt` and `updatedAt` timestamps
   - Sensible domain columns based on the module name (ask if unclear)
   - Explicit snake_case table name
   - `@Exclude()` on sensitive fields

2. **`src/$ARGUMENTS/dto/create-$ARGUMENTS.dto.ts`**
   - class-validator decorators on every field
   - No `id`, `createdAt`, `updatedAt` (those are server-managed)

3. **`src/$ARGUMENTS/dto/update-$ARGUMENTS.dto.ts`**
   - `extends PartialType(Create$ArgumentsDto)` from `@nestjs/mapped-types`

4. **`src/$ARGUMENTS/$ARGUMENTS.service.ts`**
   - Full CRUD: `findAll()`, `findOne(id)`, `create(dto)`, `update(id, dto)`, `remove(id)`
   - Inject `@InjectRepository($ArgumentsEntity)`
   - Throw `NotFoundException` when entity not found

5. **`src/$ARGUMENTS/$ARGUMENTS.controller.ts`**
   - `@Controller('$arguments')` (kebab-case, plural)
   - GET /, GET /:id, POST /, PATCH /:id, DELETE /:id
   - Use `ParseUUIDPipe` on id params
   - `@HttpCode(HttpStatus.CREATED)` on POST
   - `@HttpCode(HttpStatus.NO_CONTENT)` on DELETE

6. **`src/$ARGUMENTS/$ARGUMENTS.module.ts`**
   - `TypeOrmModule.forFeature([$ArgumentsEntity])`
   - Declare controller and service

After generating all files:
- Show the exact `import` line to add to `src/app.module.ts`
- Remind to run `npm run migration:generate -- src/database/migrations/Add$ArgumentsTable`
FEATURE

echo "✅  Created: .claude/commands/feature.md  → use /feature <name>"

# ── /entity ───────────────────────────────────────────────────────────────────
cat > "$CMD/entity.md" << 'ENTITY'
---
description: Generate a single TypeORM entity file for the given name and optional field list
---

Generate a TypeORM entity for: **$ARGUMENTS**

Format of $ARGUMENTS: `EntityName [field:type field:type ...]`
Examples:
  - `Post title:string body:text published:boolean author:relation`
  - `Product name:string price:number stock:number`

Read `CLAUDE.md` for entity conventions before generating.

Rules:
- File: `src/<name>/<name>.entity.ts` (kebab-case filename, PascalCase class)
- Always include: `id` (UUID), `createdAt`, `updatedAt`
- Map field types: string→varchar, text→text, number→decimal/int, boolean→boolean, relation→stub with TODO
- Use explicit column names in snake_case via `{ name: 'column_name' }`
- Add `@Exclude()` to any field named `password`, `hash`, `secret`, `token`
- Explicit table name in snake_case plural (e.g. `@Entity('blog_posts')`)
- Export a `typeorm:import` line to add to `data-source.ts` entities array

After the entity, show:
1. The import line needed in the feature module
2. The migration command to run
ENTITY

echo "✅  Created: .claude/commands/entity.md  → use /entity <Name> [fields]"

# ── /docs ─────────────────────────────────────────────────────────────────────
cat > "$CMD/docs.md" << 'DOCS'
---
description: Fetch and summarise official documentation for the given NestJS / TypeORM topic
---

Topic requested: **$ARGUMENTS**

Step 1 — Identify the best official documentation URL for this topic.
Use the table in `CLAUDE.md` under "Key NestJS Doc Sections" and "TypeORM Doc Sections".
If the topic maps to multiple pages, list all relevant URLs.

Step 2 — Fetch the content of each URL using WebFetch.

Step 3 — Produce a focused summary containing:

### 📖 Topic: <topic>
**Source:** <URL(s)>

#### What it is
One paragraph explanation.

#### When to use it in this project
Concrete advice for earth-dna-BE (reference actual modules/entities we have).

#### Code pattern
A minimal, copy-paste-ready TypeScript + NestJS code snippet following our project conventions.

#### Gotchas / common mistakes
Bullet list of things to watch out for.

#### Related topics
Links to adjacent docs pages worth knowing.

Step 4 — Ask: "Would you like me to apply this pattern to a specific module?"
DOCS

echo "✅  Created: .claude/commands/docs.md  → use /docs <topic>"

echo ""
echo "🎉  All 4 slash commands ready!"
echo ""
echo "Available commands in Claude Code:"
echo "  /sync           — summarise current repo state"
echo "  /feature <name> — scaffold a full CRUD module"
echo "  /entity <name>  — generate a TypeORM entity"
echo "  /docs <topic>   — fetch + summarise official docs"
